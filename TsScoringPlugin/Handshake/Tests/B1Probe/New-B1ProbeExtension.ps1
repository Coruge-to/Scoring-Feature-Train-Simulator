# PHASE SI-B1 (B1-probe) - makes the PROBE copy of the product Extension file: Telemetry\Legacy\src\LegacyTelemetryExtension.cs + five anchored insertions that wire the observation-only
# B1ProbeHook (Tests\B1Probe\src\B1ProbeHost.cs). The product file is only READ; the copy goes to a generated (ignored) place and is compiled by the probe project only.
# Every anchor must be found EXACTLY ONCE, otherwise nothing is written (a product Extension that changed shape must be re-examined by a human, never patched blindly).
# Verify mode (-Verify) reverses the five insertions on an existing copy and reports whether it equals the product file (used by the offline tests).
# This script is ASCII-only on purpose.
param(
    [string]$Root = '',
    [string]$Output = '',
    [switch]$Verify
)

$ErrorActionPreference = 'Stop'
if ($Root -eq '') { $Root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent }      # Tests\B1Probe -> Tests -> Handshake
$src = Join-Path $Root 'Telemetry\Legacy\src\LegacyTelemetryExtension.cs'
if ($Output -eq '') { $Output = Join-Path $PSScriptRoot 'obj\LegacyTelemetryExtension.B1Probe.g.cs' }
$HookType = 'TSScoringPlugin.Telemetry.B1Probe.B1ProbeHook'

$header = "// GENERATED by Tools\New-B1ProbeExtension.ps1 from Telemetry\Legacy\src\LegacyTelemetryExtension.cs (five anchored insertions). B1-PROBE OBSERVATION BUILD ONLY. Do not edit; do not commit.`n"

# each edit: the product text (exactly once) -> the probe text
$edits = @(
    @{ Name = 'field'; Old = "        private readonly FileTelemetryDiag diag = new FileTelemetryDiag();`n";
       New = "        private readonly FileTelemetryDiag diag = new FileTelemetryDiag();`n        private readonly $HookType b1probe = new $HookType();      // B1-probe (observation build only)`n" },
    @{ Name = 'tap'; Old = "session = new LegacyTelemetrySession(api, sink, delegate";
       New = "session = new LegacyTelemetrySession(api, b1probe.TapSink(sink), delegate" },
    @{ Name = 'attach'; Old = "            diag.Event(`"TEL_INIT`", ";
       New = "            try { b1probe.Attach(hacker, Native, session); } catch { }      // B1-probe (observation build only)`n            diag.Event(`"TEL_INIT`", " },
    @{ Name = 'tick'; Old = "                session.OnTick(elapsed);`n";
       New = "                try { b1probe.BeginTick(elapsed); } catch { }      // B1-probe: the one requested call sequence (if a request file exists) BEFORE the session reads this Tick`n                try { session.OnTick(elapsed); } finally { try { b1probe.EndTick(); } catch { } }`n" },
    @{ Name = 'dispose'; Old = "            try { session.OnDispose(); } catch { }`n";
       New = "            try { b1probe.OnDispose(); } catch { }      // B1-probe: no host call after this line`n            try { session.OnDispose(); } catch { }`n" }
)

function CountOf([string]$text, [string]$needle) {
    $n = 0; $i = 0
    while (($i = $text.IndexOf($needle, $i, [StringComparison]::Ordinal)) -ge 0) { $n++; $i += $needle.Length }
    return $n
}

$product = [IO.File]::ReadAllText($src).Replace("`r`n", "`n")

if ($Verify) {
    if (-not (Test-Path -LiteralPath $Output -PathType Leaf)) { Write-Host 'VERIFY: the probe copy does not exist.'; exit 1 }
    $copy = [IO.File]::ReadAllText($Output).Replace("`r`n", "`n")
    if (-not $copy.StartsWith($header, [StringComparison]::Ordinal)) { Write-Host 'VERIFY: header missing.'; exit 1 }
    $rev = $copy.Substring($header.Length)
    foreach ($e in $edits) {
        if ((CountOf $rev $e.New) -ne 1) { Write-Host ('VERIFY: the insertion ' + $e.Name + ' is not present exactly once.'); exit 1 }
        $rev = $rev.Replace($e.New, $e.Old)
    }
    if ($rev -ceq $product) { Write-Host 'VERIFY: the probe copy is the product file plus exactly the five insertions.'; exit 0 }
    Write-Host 'VERIFY: after reversing the five insertions the copy differs from the product file.'
    exit 1
}

$out = $product
foreach ($e in $edits) {
    $n = CountOf $out $e.Old
    if ($n -ne 1) { Write-Host ('REFUSED: the anchor ' + $e.Name + ' was found ' + $n + ' times (must be exactly 1). Nothing written.'); exit 1 }
    $out = $out.Replace($e.Old, $e.New)
}
$dir = Split-Path $Output -Parent
New-Item -ItemType Directory -Force $dir | Out-Null
[IO.File]::WriteAllText($Output, $header + $out, (New-Object Text.UTF8Encoding($false)))
Write-Host ('Wrote ' + $Output)
exit 0
